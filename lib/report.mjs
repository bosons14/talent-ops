// Shortlist rendering: Markdown (for reading / the agent) and CSV (for spreadsheets / ATS import).
import { fmt } from './score.mjs';

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const csvCell = (v) => {
  const s = String(v ?? '');
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export function links(c) {
  const h = c.handles;
  const out = [];
  if (h.github) out.push(`[GitHub](https://github.com/${h.github})`);
  if (h.gitlab) out.push(`[GitLab](https://gitlab.com/${h.gitlab})`);
  if (h.gitea) out.push(`[Gitea](https://${h.gitea})`);
  if (h.bitbucket) out.push(`[Bitbucket](https://bitbucket.org/${h.bitbucket})`);
  if (h.devto) out.push(`[DEV](https://dev.to/${h.devto})`);
  if (h.medium) out.push(`[Medium](https://medium.com/@${h.medium})`);
  if (h.substack) out.push(`[Substack](https://${h.substack.includes('.') ? h.substack : h.substack + '.substack.com'})`);
  if (h.hashnode) out.push(`[Hashnode](https://hashnode.com/@${h.hashnode})`);
  if (h.twitter) out.push(`[X](https://x.com/${h.twitter})`);
  for (const w of c.websites.slice(0, 2)) out.push(`[${w}](https://${w})`);
  return out.join(' · ');
}

export function renderMarkdown({ shortlist, blogs, cfg, meta }) {
  const L = [];
  L.push(`# Talent shortlist — ${meta.date}`);
  L.push('');
  L.push(`**Search:** ${cfg.topics.map((t) => t.name).join(', ')}  `);
  if (meta.location) L.push(`**Location filter:** ${meta.location}  `);
  L.push(`**Pool:** ${meta.pool} people from ${meta.runs} scout run(s) · showing top ${shortlist.length}  `);
  L.push(`**Sources:** ${meta.platforms.join(', ')}`);
  L.push('');
  L.push('> Scores rank *public evidence*, not ability. Stars and followers favour visible, English-language, open-source work. Read the evidence before contacting anyone.');
  L.push('');
  L.push('| # | Candidate | Score | Code | Writing | Location | Highlights | Status |');
  L.push('|---|---|---|---|---|---|---|---|');
  shortlist.forEach((c, i) => {
    L.push(`| ${i + 1} | **${esc(c.name)}**<br>\`${c.id}\` | ${c.score} | ${c.components.code} | ${c.components.writing} | ${esc(c.profile.location || '—')} | ${esc(c.why.slice(0, 2).join('; '))} | ${c.pipeline_status || ''} |`);
  });
  L.push('');
  L.push('## Details');
  shortlist.forEach((c, i) => {
    L.push('');
    L.push(`### ${i + 1}. ${c.name} — ${c.score}`);
    L.push(links(c) || '_no links_');
    L.push('');
    const p = c.profile;
    const facts = [p.company && `Company: ${p.company}`, p.location && `Location: ${p.location}`, p.hireable && 'Marked “available for hire” on GitHub', p.public_email && `Public email: ${p.public_email}`].filter(Boolean);
    if (facts.length) L.push(facts.join(' · '));
    if (p.bio) L.push(`> ${esc(p.bio)}`);
    L.push('');
    L.push(`Components — code ${c.components.code} · writing ${c.components.writing} · influence ${c.components.influence} · topic coverage ${c.components.relevance} · builds & writes ${c.components.cross ? 'yes' : 'no'}`);
    for (const w of c.why) L.push(`- ${esc(w)}`);
    const repos = c.repos.filter((r) => !r.owner_is_org).slice(0, 3);
    if (repos.length) {
      L.push('', '**Repos**');
      for (const r of repos) L.push(`- [${r.full_name}](${r.url}) — ${fmt(r.stars)} ${r.metric === 'watchers' ? 'watchers' : '★'}${r.language ? ` · ${r.language}` : ''}${r.description ? ` — ${esc(r.description).slice(0, 120)}` : ''}`);
    }
    if (c.contributions.length) {
      L.push('', '**Contributions to popular repos**');
      for (const k of c.contributions.slice(0, 3)) L.push(`- [${k.full_name}](${k.url}) — ${k.contributions} commits (${fmt(k.stars)} ★)`);
    }
    if (c.posts.length) {
      L.push('', '**Writing**');
      for (const post of c.posts.slice(0, 3)) L.push(`- [${esc(post.title)}](${post.url}) — ${post.platform}${post.engagement ? `, ${post.engagement} ${post.engagement_label}${post.engagement_source ? ` on ${post.engagement_source}` : ''}` : ''}${post.published_at ? `, ${post.published_at.slice(0, 10)}` : ''}`);
    }
    if (c.possible_matches.length) L.push('', `_Possible same person (name match only — verify): ${c.possible_matches.join(', ')}_`);
  });
  if (blogs.length) {
    L.push('', '## Blogs not yet linked to a person', '', 'Popular on-topic blogs where no code profile or author handle was found. Open them to identify the author, then add `{ "url": "<feed>", "github": "<login>" }` to `sources.feeds.urls`.', '');
    for (const b of blogs) L.push(`- **${b.websites[0] || b.id}** — ${b.posts.length} post(s); top: [${esc(b.posts[0]?.title)}](${b.posts[0]?.url}) (${b.posts[0]?.engagement ?? 0} ${b.posts[0]?.engagement_label || ''})`);
  }
  L.push('', '---', `Generated by talent-ops · ${meta.generated}`);
  return L.join('\n') + '\n';
}

export const CSV_COLUMNS = ['rank', 'id', 'name', 'score', 'code', 'writing', 'influence', 'topic_coverage', 'location', 'company', 'followers', 'hireable', 'public_email', 'github', 'gitlab', 'devto', 'medium', 'substack', 'hashnode', 'twitter', 'website', 'top_repo', 'top_repo_stars', 'top_post', 'top_post_url', 'topics', 'status'];

export function renderCsv(shortlist) {
  const rows = shortlist.map((c, i) => {
    const r = c.repos.find((x) => !x.owner_is_org) || c.contributions[0];
    const p = c.posts[0];
    return [i + 1, c.id, c.name, c.score, c.components.code, c.components.writing, c.components.influence, c.components.relevance, c.profile.location, c.profile.company, c.profile.followers, c.profile.hireable, c.profile.public_email, c.handles.github, c.handles.gitlab, c.handles.devto, c.handles.medium, c.handles.substack, c.handles.hashnode, c.handles.twitter, c.websites[0], r?.full_name, r?.stars, p?.title, p?.url, c.topics_evidenced.join('; '), c.pipeline_status];
  });
  return [CSV_COLUMNS, ...rows].map((r) => r.map(csvCell).join(',')).join('\n') + '\n';
}
